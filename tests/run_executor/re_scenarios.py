def s_event_log_unwritable(ctx):
    class Broken:
        def __init__(self, *a, **k):
            self.complete, self.path = False, ctx.out / "run_events.jsonl"

        def emit(self, *a, **k):
            return False

    ctx.mp.setattr(executor_module, "EventLog", Broken)
    return _go(ctx)


def s_event_log_flaky_after_run(ctx):
    real = executor_module.EventLog

    class Flaky(real):
        def emit(self, event, **fields):
            if event == "runner_finished":
                self.complete = False
                return False
            return super().emit(event, **fields)

    ctx.mp.setattr(executor_module, "EventLog", Flaky)
    return _go(ctx)


