SCENARIOS = {name[2:]: fn for name, fn in sorted(globals().items()) if name.startswith("s_") and callable(fn)}


def run_scenario(name: str, tmp: Path) -> dict:
    import pytest

    repo = make_repo(tmp)
    out = tmp / "run"
    with pytest.MonkeyPatch.context() as mp:
        ctx = SimpleNamespace(tmp=tmp, repo=repo, out=out, mp=mp)
        outcome = SCENARIOS[name](ctx)
    return normalize(outcome, out, tmp)
