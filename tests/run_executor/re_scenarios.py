def s_post_collect_fails(ctx):
    real, calls = executor_module.collect_provenance, []

    def second_fails(**kwargs):
        calls.append(1)
        if len(calls) == 2:
            raise OSError("post")
        return real(**kwargs)

    ctx.mp.setattr(executor_module, "collect_provenance", second_fails)
    return _go(ctx)


