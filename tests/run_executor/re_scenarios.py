def _scrub(value, tmp: Path):
    if isinstance(value, str):
        return value.replace(str(tmp), "<TMP>").replace(str(tmp.resolve()), "<TMP>")
    if isinstance(value, dict):
        return {k: _scrub(v, tmp) for k, v in value.items()}
    if isinstance(value, (list, tuple)):
        return [_scrub(v, tmp) for v in value]
    return value


_HEX64 = __import__("re").compile(r"[0-9a-f]{64}")


def _normalize_artifacts(report: dict | None) -> dict | None:
    """Hash values depend on run timestamps and the platform, so they are replaced by placeholders AFTER their
    format is asserted. Names, order, required flags, the algorithm, the format text and the errors stay in."""
    if report is None or "artifacts" not in report:
        return report
    block = report["artifacts"]
    for entry in block["files"]:
        assert isinstance(entry["bytes"], int) and entry["bytes"] >= 0 and _HEX64.fullmatch(entry["sha256"]), entry["name"]
        entry["bytes"], entry["sha256"] = "<bytes>", "<sha256>"
    assert _HEX64.fullmatch(block["artifact_digest"])
    block["artifact_digest"] = "<sha256>"
    return report


def normalize(outcome, out: Path, tmp: Path) -> dict:
    data = dict(
        status=outcome.status, failed_stage=outcome.failed_stage, detail=outcome.detail, claimed=outcome.claimed,
        analysis_eligible=outcome.analysis_eligible, warnings=list(outcome.warnings),
        report=outcome.report.to_dict() if outcome.report is not None else None,
        report_path=outcome.report_path.name if outcome.report_path else None,
        events_path=outcome.events_path.name if outcome.events_path else None,
        provenance_path=outcome.provenance_path.name if outcome.provenance_path else None,
        has_provenance_record=outcome.provenance_record is not None,
        results_returned=len(outcome.results) if outcome.results is not None else None,
        loaded_valid_records=outcome.loaded.report.valid_records if outcome.loaded is not None else None,
        files=sorted(p.name for p in out.iterdir()) if out.is_dir() else None,
        episodes_lines=(out / "episodes.jsonl").read_text(encoding="utf-8").count("\n") if (out / "episodes.jsonl").is_file() else None,
        events=[json.loads(l) for l in (out / "run_events.jsonl").read_text(encoding="utf-8").splitlines()] if (out / "run_events.jsonl").is_file() else None,
    )
    data = _scrub(json.loads(json.dumps(data, sort_keys=True)), tmp)
    data["report"] = _normalize_artifacts(data["report"])
    return data


def _go(ctx, runner=None, *, run_id=RUN_ID, out=None, **extra):
    options = extra.pop("provenance_options", provenance_options())
    return execute_mock_run(
        run_fn=runner or Runner(3), cfg=extra.pop("cfg", cfg_double()), scenarios=[], client=extra.pop("client", MOCK),
        run_dir=out or ctx.out, run_id=run_id, repo_root=ctx.repo, clock=CLOCK, provenance_options=options, **extra,
    )


def _raise_first(ctx, name):
    def refuse(*args, **kwargs):
        raise OSError("disk problem")

    ctx.mp.setattr(executor_module, name, refuse)


